
const Loan = require("../models/Loan");
const CibilSimulator = require("../models/CibilSimulator");

const getChatbotResponse = async (req, res) => {
  try {
    const userId = req.user.id;

    const { message, language = "en" } = req.body;

    if (!message || !message.trim()) {
      return res.status(400).json({
        success: false,
        message: "Please enter a question.",
      });
    }

    const loans = await Loan.find({
      user: userId,
    }).sort({
      dueDate: 1,
    });

    const scoreProfile = await CibilSimulator.findOne({
      user: userId,
    });

    const currentScore = scoreProfile?.currentScore || 0;

    const totalOutstanding = loans.reduce(
      (sum, loan) => sum + (loan.outstandingAmount || 0),
      0
    );

    const totalMonthlyEMI = loans.reduce(
      (sum, loan) =>
        sum + (loan.emiAmount || loan.minimumDue || 0),
      0
    );

    const missedPayments = loans.reduce(
      (sum, loan) => sum + (loan.missedPayments || 0),
      0
    );

    const latePayments = loans.reduce(
      (sum, loan) => sum + (loan.latePayments || 0),
      0
    );

    const onTimePayments = loans.reduce(
      (sum, loan) => sum + (loan.onTimePayments || 0),
      0
    );

    const lowerMessage = message.toLowerCase();

    let response = "";

    /*
     * English
     */
    if (language === "en") {
      if (
        lowerMessage.includes("score") ||
        lowerMessage.includes("cibil")
      ) {
        response =
          `Your current simulated CIBIL score is ${currentScore}. ` +
          `This score is generated by CrediGuide based on your loan and payment behavior. ` +
          `It is not your official TransUnion CIBIL score.`;
      } else if (
        lowerMessage.includes("loan") &&
        (lowerMessage.includes("how many") ||
          lowerMessage.includes("number") ||
          lowerMessage.includes("count"))
      ) {
        response =
          `You currently have ${loans.length} loan${
            loans.length === 1 ? "" : "s"
          } recorded in CrediGuide.`;
      } else if (
        lowerMessage.includes("emi") ||
        lowerMessage.includes("monthly payment")
      ) {
        response =
          `Your combined monthly EMI requirement is approximately ₹${totalMonthlyEMI.toLocaleString(
            "en-IN"
          )}.`;
      } else if (
        lowerMessage.includes("outstanding") ||
        lowerMessage.includes("debt")
      ) {
        response =
          `Your total outstanding loan balance is approximately ₹${totalOutstanding.toLocaleString(
            "en-IN"
          )}.`;
      } else if (
        lowerMessage.includes("missed") ||
        lowerMessage.includes("late payment")
      ) {
        response =
          `You have ${missedPayments} missed payment${
            missedPayments === 1 ? "" : "s"
          } and ${latePayments} late payment${
            latePayments === 1 ? "" : "s"
          } recorded. ` +
          `Try to make future payments on or before their due dates.`;
      } else if (
        lowerMessage.includes("on time") ||
        lowerMessage.includes("payment history")
      ) {
        response =
          `You have ${onTimePayments} on-time payment${
            onTimePayments === 1 ? "" : "s"
          } recorded. ` +
          `Consistent on-time payments can improve your simulated credit behavior.`;
      } else if (
        lowerMessage.includes("improve") ||
        lowerMessage.includes("increase")
      ) {
        response =
          "To improve your simulated credit score, focus on making every EMI payment on time, " +
          "avoiding missed payments, reducing outstanding balances and keeping credit-card utilization under control.";
      } else if (
        lowerMessage.includes("help") ||
        lowerMessage.includes("what can you do")
      ) {
        response =
          "I can help you understand your simulated credit score, loans, EMIs, outstanding debt, " +
          "payment behavior and repayment strategies.";
      } else {
        response =
          "I can help with your simulated credit score, loans, EMIs, outstanding balance, " +
          "payment history and debt repayment planning. Try asking something like " +
          '"What is my score?", "How much EMI do I pay?", or "How can I improve my score?"';
      }
    }

    /*
     * Telugu
     */
    else if (language === "te") {
      if (
        lowerMessage.includes("score") ||
        lowerMessage.includes("cibil")
      ) {
        response =
          `మీ ప్రస్తుత సిమ్యులేటెడ్ CIBIL స్కోర్ ${currentScore}. ` +
          "ఈ స్కోర్ CrediGuide లో మీ లోన్ మరియు చెల్లింపు ప్రవర్తన ఆధారంగా రూపొందించబడుతుంది. " +
          "ఇది అధికారిక TransUnion CIBIL స్కోర్ కాదు.";
      } else if (
        lowerMessage.includes("loan") ||
        lowerMessage.includes("లోన్")
      ) {
        response =
          `మీ CrediGuide ఖాతాలో ప్రస్తుతం ${loans.length} లోన్${
            loans.length === 1 ? "" : "లు"
          } నమోదు చేయబడ్డాయి.`;
      } else if (
        lowerMessage.includes("emi") ||
        lowerMessage.includes("ఈఎంఐ")
      ) {
        response =
          `మీ మొత్తం నెలవారీ EMI సుమారు ₹${totalMonthlyEMI.toLocaleString(
            "en-IN"
          )}.`;
      } else if (
        lowerMessage.includes("outstanding") ||
        lowerMessage.includes("debt")
      ) {
        response =
          `మీ మొత్తం బాకీ లోన్ మొత్తం సుమారు ₹${totalOutstanding.toLocaleString(
            "en-IN"
          )}.`;
      } else if (
        lowerMessage.includes("improve") ||
        lowerMessage.includes("మెరుగుపరచ")
      ) {
        response =
          "మీ సిమ్యులేటెడ్ క్రెడిట్ స్కోర్‌ను మెరుగుపరచడానికి EMIలను గడువు తేదీకి ముందు చెల్లించండి, " +
          "చెల్లింపులు మిస్ కాకుండా చూసుకోండి మరియు బాకీ మొత్తాన్ని తగ్గించండి.";
      } else {
        response =
          "మీ సిమ్యులేటెడ్ క్రెడిట్ స్కోర్, లోన్లు, EMIలు మరియు చెల్లింపు ప్రవర్తన గురించి నేను సహాయం చేయగలను.";
      }
    }

    /*
     * Hindi
     */
    else if (language === "hi") {
      if (
        lowerMessage.includes("score") ||
        lowerMessage.includes("cibil")
      ) {
        response =
          `आपका वर्तमान सिम्युलेटेड CIBIL स्कोर ${currentScore} है। ` +
          "यह स्कोर CrediGuide में आपके लोन और भुगतान व्यवहार के आधार पर बनाया जाता है। " +
          "यह आपका आधिकारिक TransUnion CIBIL स्कोर नहीं है।";
      } else if (
        lowerMessage.includes("loan") ||
        lowerMessage.includes("लोन")
      ) {
        response =
          `आपके CrediGuide खाते में वर्तमान में ${loans.length} लोन दर्ज हैं।`;
      } else if (
        lowerMessage.includes("emi") ||
        lowerMessage.includes("ईएमआई")
      ) {
        response =
          `आपकी कुल मासिक EMI लगभग ₹${totalMonthlyEMI.toLocaleString(
            "en-IN"
          )} है।`;
      } else if (
        lowerMessage.includes("outstanding") ||
        lowerMessage.includes("debt")
      ) {
        response =
          `आपकी कुल बकाया लोन राशि लगभग ₹${totalOutstanding.toLocaleString(
            "en-IN"
          )} है।`;
      } else if (
        lowerMessage.includes("improve") ||
        lowerMessage.includes("बढ़ाएं") ||
        lowerMessage.includes("सुधार")
      ) {
        response =
          "अपने सिम्युलेटेड क्रेडिट स्कोर को बेहतर बनाने के लिए EMI समय पर भरें, " +
          "भुगतान मिस न करें और बकाया राशि कम करने की कोशिश करें।";
      } else {
        response =
          "मैं आपके सिम्युलेटेड क्रेडिट स्कोर, लोन, EMI और भुगतान व्यवहार के बारे में मदद कर सकता हूँ।";
      }
    } else {
      response =
        "Please select English, Telugu or Hindi as your chatbot language.";
    }

    return res.json({
      success: true,
      response,
      language,
    });
  } catch (error) {
    console.error("Chatbot Error:", error);

    return res.status(500).json({
      success: false,
      message: "Unable to process your question.",
    });
  }
};

module.exports = {
  getChatbotResponse,
};
